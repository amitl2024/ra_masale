const categoryCode: Record<CategorySlug, string> = {
  "spices-masalas": "SM",
  "ready-mix": "RM",
  pickles: "PK",
  papads: "PP",
  other: "OT",
};

export const products: Product[] = seeds.map((s, i) => ({
  storageInstructions: DRY_STORAGE,
  vegetarian: true,
  availability: "available",
  ...s,
  catalogueNo: i + 1,
  productCode: `RA-${categoryCode[s.category]}-${String(i + 1).padStart(3, "0")}`,
}));

export function getProduct(slug: string) {
  return products.find((p) => p.slug === slug);
}

export function productsByCategory(slug: CategorySlug) {
  return products.filter((p) => p.category === slug);
}

/** Category hero product — prefers one with real photography */
export function leadProduct(slug: CategorySlug) {
  const list = productsByCategory(slug);
  return list.find((p) => p.images?.length) ?? list[0];
}

export function featuredProducts() {
  return products.filter((p) => p.featured);
}

export function relatedProducts(product: Product, limit = 4) {
  const paired = (product.pairsWith ?? [])
    .map(getProduct)
    .filter((p): p is Product => Boolean(p));
  const sameCategory = products
    .filter((p) => p.category === product.category && p.slug !== product.slug && !paired.includes(p))
    .sort((a, b) => Number(Boolean(b.images?.length)) - Number(Boolean(a.images?.length)));
  return [...paired, ...sameCategory].slice(0, limit);
}
